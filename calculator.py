def add(a, b):
    return a + b

def subtract(a, b):
    return a - b

def multiply(a, b):
    return a * b

def divide(a, b):
    return a / b

def power(a, b):
    return a ** b

def modulo(a, b):
    return a % b

def square(a):
    return a * a

def cube(a):
    return a ** 3

def average(a, b):
    return (a + b) / 2